"""Online event-only front-end (paper Sec. 4.1).

Every event chunk ``C`` goes through

1. eFAST corner detection ``F subset C`` (:mod:`espinslam.efast`),
2. same-polarity density filtering ``G subset F`` (Eq. 6),
3. HDBSCAN spatio-temporal clustering of ``G`` into tracklets ``M_c``,
4. association/merging of the tracklets into the global pool of tracks ``H``.

Tracks store their *events* (not centroids) because the back-end turns every
event of every track into a virtual-camera observation (Sec. 4.2.2). Each track
is a circular buffer of at most ``sigma_retain`` events (Sec. 4.2.7).
"""

from __future__ import annotations

from dataclasses import dataclass
import warnings

import numpy as np
from scipy.spatial import cKDTree
from sklearn.cluster import HDBSCAN

from .config import FrontendConfig
from .efast import EFastDetector


def _small_median(values: np.ndarray) -> float:
    ordered = np.sort(values)
    middle = ordered.size // 2
    if ordered.size % 2:
        return float(ordered[middle])
    return 0.5 * float(ordered[middle - 1] + ordered[middle])


class FeatureTrack:
    """A track ``H_u``: events assumed to be generated by one world point."""

    __slots__ = ("track_id", "polarity", "t", "x", "y", "revision", "_head")

    def __init__(self, track_id: int, polarity: int, t: np.ndarray,
                 x: np.ndarray, y: np.ndarray):
        self.track_id = int(track_id)
        self.polarity = int(polarity)
        self.t = np.asarray(t, dtype=np.float64)
        self.x = np.asarray(x, dtype=np.float32)
        self.y = np.asarray(y, dtype=np.float32)
        self.revision = 0
        self._head: tuple[int, int, float, float] | None = None

    @property
    def size(self) -> int:
        return int(self.t.size)

    @property
    def latest_t(self) -> float:
        return float(self.t[-1])

    @property
    def earliest_t(self) -> float:
        return float(self.t[0])

    def head(self, count: int) -> tuple[float, float]:
        """Median position of the newest ``count`` events (cached per revision)."""

        cached = self._head
        if cached is None or cached[0] != self.revision or cached[1] != count:
            cached = (self.revision, count, _small_median(self.x[-count:]),
                      _small_median(self.y[-count:]))
            self._head = cached
        return cached[2], cached[3]

    def tail_descriptor(self, count: int, time_scale: float) -> np.ndarray:
        """Mean of the latest ``N_sigma`` (t, x, y) events from eSfO Eq. (3).

        The cited front-end calls this the *tail* descriptor of an earlier
        cluster.  Timestamps are stored in seconds, so the declared scale maps
        them to the coordinate used alongside pixels.
        """

        take = slice(max(0, self.size - count), self.size)
        return np.asarray((
            float(np.mean(self.x[take])),
            float(np.mean(self.y[take])),
            float(np.mean(self.t[take])) * float(time_scale),
        ))

    def append(self, t: np.ndarray, x: np.ndarray, y: np.ndarray, retain: int) -> None:
        self.t = np.concatenate((self.t, t))[-retain:]
        self.x = np.concatenate((self.x, np.asarray(x, dtype=np.float32)))[-retain:]
        self.y = np.concatenate((self.y, np.asarray(y, dtype=np.float32)))[-retain:]
        self.revision += 1


class TrackPool:
    """Global pool ``H`` with bounded per-track memory."""

    def __init__(self, retain: int):
        self.retain = int(retain)
        self.tracks: dict[int, FeatureTrack] = {}
        self.active: set[int] = set()
        self.next_id = 0
        self.newest_time = -np.inf
        self.version = 0

    def __len__(self) -> int:
        return len(self.tracks)

    def add(self, polarity: int, t: np.ndarray, x: np.ndarray, y: np.ndarray) -> int:
        track = FeatureTrack(self.next_id, polarity, t[-self.retain:], x[-self.retain:],
                             y[-self.retain:])
        self.tracks[track.track_id] = track
        self.active.add(track.track_id)
        self.next_id += 1
        self.version += 1
        self.newest_time = max(self.newest_time, track.latest_t)
        return track.track_id

    def extend(self, track_id: int, t: np.ndarray, x: np.ndarray, y: np.ndarray) -> None:
        track = self.tracks[track_id]
        track.append(t, x, y, self.retain)
        self.active.add(track_id)
        self.version += 1
        self.newest_time = max(self.newest_time, track.latest_t)

    def remove(self, track_ids) -> None:
        removed = False
        for track_id in track_ids:
            if self.tracks.pop(int(track_id), None) is not None:
                self.version += 1
                removed = True
            self.active.discard(int(track_id))
        if removed:
            # Eq. (12) is relative to the newest event still present in H.
            # Keeping the timestamp of a removed newest track would make the
            # next cutoff too recent and could cascade into over-forgetting.
            self.newest_time = max(
                (track.latest_t for track in self.tracks.values()), default=-np.inf,
            )

    def merge(self, track_ids) -> int:
        """Landmark association (Sec. 4.2.6): ``H_u2 = H_u1 U H_u2``."""

        track_ids = sorted({int(value) for value in track_ids if int(value) in self.tracks})
        if not track_ids:
            raise KeyError("no track to merge")
        keep = self.tracks[track_ids[0]]
        if len(track_ids) == 1:
            return keep.track_id
        members = [self.tracks[value] for value in track_ids]
        t = np.concatenate([member.t for member in members])
        x = np.concatenate([member.x for member in members])
        y = np.concatenate([member.y for member in members])
        order = np.argsort(t, kind="stable")[-self.retain:]
        newest = max(members, key=lambda member: member.latest_t)
        keep.t, keep.x, keep.y = t[order], x[order], y[order]
        keep.polarity = newest.polarity
        keep.revision += 1
        if any(value in self.active for value in track_ids):
            self.active.add(keep.track_id)
        self.remove(track_ids[1:])
        self.version += 1
        return keep.track_id

    def forget(self, cutoff_time: float) -> list[int]:
        """Discard tracks whose newest event is older than ``cutoff_time``."""

        stale = [track_id for track_id, track in self.tracks.items()
                 if track.latest_t < cutoff_time]
        self.remove(stale)
        return stale

    def events(self) -> np.ndarray:
        """All events of all tracks, ``A`` in Eq. (7), as [N,3] t/x/y rows."""

        if not self.tracks:
            return np.empty((0, 3), dtype=np.float64)
        tracks = list(self.tracks.values())
        return np.column_stack((
            np.concatenate([track.t for track in tracks]),
            np.concatenate([track.x for track in tracks]).astype(np.float64),
            np.concatenate([track.y for track in tracks]).astype(np.float64),
        ))

    def snapshot(self) -> list[FeatureTrack]:
        return sorted(self.tracks.values(), key=lambda track: track.track_id)


def density_filter(t: np.ndarray, x: np.ndarray, y: np.ndarray, p: np.ndarray,
                   radius: float, *, per_polarity_mean: bool = False) -> np.ndarray:
    """Eq. (6): keep corners whose same-polarity density reaches the mean ``mu_D``.

    ``D(e_i) = (1/lambda) * #{e_q in F : |e_q - e_i| <= lambda, p_q = p_i}``;
    corners with ``D < mu_D`` are removed.  The cited eSfO front-end computes
    ``mu_D`` independently for each polarity, selected by
    ``per_polarity_mean=True`` in the paper-reference profile.  A global mean
    remains available solely for historical experimental replay.
    """

    count = t.size
    if count < 2:
        return np.ones(count, dtype=bool)
    scores = np.zeros(count, dtype=np.float64)
    thresholds = np.zeros(count, dtype=np.float64)
    points = np.column_stack((x, y)).astype(np.float64)
    for polarity in (0, 1):
        indices = np.flatnonzero(p == polarity)
        if indices.size == 0:
            continue
        tree = cKDTree(points[indices])
        neighbours = tree.query_ball_point(points[indices], radius, return_length=True)
        scores[indices] = (np.asarray(neighbours, dtype=np.float64) - 1.0) / radius
        thresholds[indices] = scores[indices].mean()
    if not per_polarity_mean:
        thresholds[:] = scores.mean()
    return scores >= thresholds


@dataclass(frozen=True)
class Tracklet:
    polarity: int
    t: np.ndarray
    x: np.ndarray
    y: np.ndarray


def cluster_tracklets(t: np.ndarray, x: np.ndarray, y: np.ndarray, p: np.ndarray,
                      config: FrontendConfig) -> list[Tracklet]:
    """HDBSCAN over (x, y, t) of the density-filtered corners of one chunk."""

    count = t.size
    minimum = config.cluster_min_size
    if config.cluster_min_samples is not None:
        minimum = max(minimum, config.cluster_min_samples + 1)
    if count < minimum:
        return []
    features = [
        x.astype(np.float64), y.astype(np.float64),
        (t - t[0]) * config.cluster_time_scale_px_per_second,
    ]
    if config.cluster_by_polarity:
        # A large polarity offset forbids clusters that mix polarities.
        features.append(p.astype(np.float64) * 1.0e6)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", FutureWarning)
        labels = HDBSCAN(
            min_cluster_size=config.cluster_min_size,
            min_samples=config.cluster_min_samples,
            cluster_selection_epsilon=config.cluster_selection_epsilon,
            copy=True,
        ).fit_predict(np.column_stack(features))
    tracklets = []
    for label in np.unique(labels):
        if label < 0:
            continue
        members = np.flatnonzero(labels == label)
        members = members[np.argsort(t[members], kind="stable")]
        polarity = int(np.mean(p[members]) >= 0.5)
        tracklets.append(Tracklet(polarity, t[members], x[members], y[members]))
    return tracklets


@dataclass(frozen=True)
class FrontendChunkStats:
    events: int
    corners: int
    dense_corners: int
    tracklets: int
    associated: int
    new_tracks: int


class EventFrontend:
    """Chunk-driven eFAST -> density -> HDBSCAN -> track association."""

    def __init__(self, width: int, height: int, config: FrontendConfig):
        self.width = int(width)
        self.height = int(height)
        self.config = config
        self.detector = EFastDetector(self.width, self.height)
        self.pool = TrackPool(config.retain_events_per_track)

    def push(self, t: np.ndarray, x: np.ndarray, y: np.ndarray,
             p: np.ndarray) -> FrontendChunkStats:
        corners = self.detector.detect(x, y, t, p)
        ct, cx, cy, cp = t[corners], x[corners], y[corners], p[corners]
        dense = density_filter(ct, cx, cy, cp, self.config.density_radius_px,
                               per_polarity_mean=self.config.density_mean_per_polarity)
        ct, cx, cy, cp = ct[dense], cx[dense], cy[dense], cp[dense]
        tracklets = cluster_tracklets(ct, cx, cy, cp, self.config)
        associated = self._associate(tracklets, float(t[0]) if t.size else 0.0)
        return FrontendChunkStats(
            int(t.size), int(corners.sum()), int(ct.size), len(tracklets),
            associated, len(tracklets) - associated,
        )

    def _associate(self, tracklets: list[Tracklet], chunk_start: float) -> int:
        if self.config.interpretation_mode == "paper":
            return self._associate_paper(tracklets)
        return self._associate_experimental(tracklets, chunk_start)

    def _associate_paper(self, tracklets: list[Tracklet]) -> int:
        """Online form of cited eSfO head/tail association (Eq. (3)).

        The mean of the first/last ``N_sigma`` spatio-temporal events forms the
        descriptor.  A new tracklet joins its nearest earlier track inside the
        forward temporal hemisphere of radius ``phi``.  eSpinSLAM does not
        specify collision handling after adapting the offline eSfO procedure
        to chunks; the neutral deterministic choice used here lets multiple
        fragments from one chunk join the same earlier track.
        """

        config = self.config
        pool = self.pool
        if not tracklets:
            return 0
        count = config.association_head_events
        scale = config.cluster_time_scale_px_per_second
        active = [pool.tracks[track_id] for track_id in sorted(pool.active)
                  if track_id in pool.tracks]
        matched: dict[int, int] = {}
        if active:
            tails = np.asarray([track.tail_descriptor(count, scale) for track in active])
            heads = np.asarray([
                (
                    float(np.mean(item.x[:count])),
                    float(np.mean(item.y[:count])),
                    float(np.mean(item.t[:count])) * scale,
                )
                for item in tracklets
            ])
            difference = heads[:, None, :] - tails[None, :, :]
            distance = np.linalg.norm(difference, axis=2)
            # A hemisphere has no backward-time half.  Whether its equatorial
            # plane and radius boundary are open or closed is not specified by
            # eSfO; the frozen interpretation admits equal descriptor times
            # and uses a strict distance < phi boundary.
            valid = ((difference[:, :, 2] >= 0.0)
                     & (distance < config.association_radius_px))
            distance = np.where(valid, distance, np.inf)
            best = np.argmin(distance, axis=1)
            for row in range(len(tracklets)):
                if np.isfinite(distance[row, best[row]]):
                    matched[row] = active[int(best[row])].track_id
        return self._apply_associations(tracklets, matched)

    def _associate_experimental(self, tracklets: list[Tracklet], chunk_start: float) -> int:
        config = self.config
        pool = self.pool
        stale = [track_id for track_id in pool.active
                 if track_id not in pool.tracks
                 or pool.tracks[track_id].latest_t < chunk_start - config.association_max_gap_seconds]
        pool.active.difference_update(stale)
        if not tracklets:
            return 0
        head = config.association_head_events
        active = [pool.tracks[track_id] for track_id in sorted(pool.active)]
        matched: dict[int, int] = {}
        if active:
            track_xy = np.asarray([track.head(head) for track in active])
            track_t = np.asarray([track.latest_t for track in active])
            track_p = np.asarray([track.polarity for track in active])
            start_xy = np.asarray([
                (_small_median(item.x[:head]), _small_median(item.y[:head]))
                for item in tracklets
            ], dtype=np.float64)
            start_t = np.asarray([item.t[0] for item in tracklets])
            start_p = np.asarray([item.polarity for item in tracklets])
            distance = np.linalg.norm(start_xy[:, None, :] - track_xy[None, :, :], axis=2)
            gap = start_t[:, None] - track_t[None, :]
            valid = (
                (distance <= config.association_radius_px)
                & (gap <= config.association_max_gap_seconds)
                & (gap >= -config.association_max_gap_seconds)
            )
            if config.cluster_by_polarity:
                valid &= start_p[:, None] == track_p[None, :]
            # Each tracklet joins its nearest compatible track. Several tracklets
            # of one chunk may merge into the same track (HDBSCAN can split one
            # corner's events), which avoids spawning duplicate fragments.
            distance = np.where(valid, distance, np.inf)
            best = np.argmin(distance, axis=1)
            for row in range(len(tracklets)):
                if np.isfinite(distance[row, best[row]]):
                    matched[row] = active[int(best[row])].track_id
        return self._apply_associations(tracklets, matched)

    def _apply_associations(self, tracklets: list[Tracklet],
                            matched: dict[int, int]) -> int:
        """Apply deterministic tracklet-to-pool associations."""

        pool = self.pool
        groups: dict[int, list[Tracklet]] = {}
        for row, item in enumerate(tracklets):
            if row in matched:
                groups.setdefault(matched[row], []).append(item)
            else:
                pool.add(item.polarity, item.t, item.x, item.y)
        for track_id, items in groups.items():
            t = np.concatenate([item.t for item in items])
            order = np.argsort(t, kind="stable")
            x = np.concatenate([item.x for item in items])[order]
            y = np.concatenate([item.y for item in items])[order]
            pool.extend(track_id, t[order], x, y)
        return len(matched)
